"""Copy agent skills into the Codex and Claude layouts.

Skills come from trazo itself (shared by every project) and from the
project's own folder ([paths] skills, agent-workflows/skills by default),
which may add skills or replace a trazo skill of the same name. Each
copy goes to every [paths] skill_targets folder (.agents/skills and
.claude/skills) with a marker file, and a marked copy of a skill neither
has is removed, also from a template folder the project dropped from its
skill_targets (the template wrote copies there); --check fails when a
copy is missing, edited or stale. `trazo update` regenerates the
copies the same way.

    trazo agents [--check]
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
from pathlib import Path

from .project import DEFAULTS, PROJECT, SKILLS_DIR, Project

MARKER_NAME = ".generated-by-sync-agent-workflows"


class SkillError(Exception):
    """A skills folder that cannot be copied."""


def marker_text(project: Project) -> str:
    return ("Generated by `trazo agents` from trazo's skills and "
            f"{project.relative('skills')}. Do not edit this copy by hand.\n")


def skills_in(folder: Path) -> dict[str, Path]:
    skills: dict[str, Path] = {}
    if not folder.is_dir():
        return skills
    for path in sorted(folder.iterdir()):
        if not path.is_dir() or path.name.startswith((".", "_")):
            continue
        if not (path / "SKILL.md").exists():
            raise SkillError(f"missing SKILL.md in {path}")
        skills[path.name] = path
    return skills


def dropped_targets(project: Project) -> list[Path]:
    """The template's skill_targets the project does not list, where an
    older template wrote copies."""
    kept = {target.resolve() for target in project.paths("skill_targets")}
    return [project.root / name for name in DEFAULTS["paths"]["skill_targets"]
            if (project.root / name).resolve() not in kept]


def canonical_skills(project: Project) -> dict[str, Path]:
    """trazo's skills, updated with the project's (the project wins).
    Refuses folders that contain one another (the project's skills, its
    skill_targets, the template targets it dropped): a copy or the pruning
    in one would overwrite another. The same folder twice is refused only
    as the skills folder and a target, whose copies would replace it."""
    own = project.path("skills")
    targets = project.paths("skill_targets")
    for target in targets:
        if target.exists() and not target.is_dir():
            raise SkillError(f"the skill target {os.path.relpath(target, project.root)} is not a folder")
    folders = [own, *targets, *dropped_targets(project)]
    for index, folder in enumerate(folders):
        for other in folders[index + 1:]:
            one, two = folder.resolve(), other.resolve()
            if one == two and not (folder is own and other in targets):
                continue  # one folder named twice (a symlinked target): nothing overwrites another
            if one.is_relative_to(two) or two.is_relative_to(one):
                raise SkillError(f"{os.path.relpath(folder, project.root)} and {os.path.relpath(other, project.root)} "
                                 "overlap: [paths] skills, skill_targets and the template's .agents/skills and "
                                 ".claude/skills may not contain one another; move one of them")
    skills = {**skills_in(SKILLS_DIR), **skills_in(own)}
    if not skills:
        raise SkillError("no skills found")
    return dict(sorted(skills.items()))


def marker_path(skill_dir: Path) -> Path:
    return skill_dir / MARKER_NAME


def is_managed(skill_dir: Path) -> bool:
    return marker_path(skill_dir).is_file()


def iter_files(path: Path) -> list[Path]:
    return sorted(p for p in path.rglob("*")
                  if p.is_file() and "__pycache__" not in p.parts and p.name != ".DS_Store")


def expected_files(source: Path, target: Path, marker: str) -> dict[Path, bytes]:
    expected: dict[Path, bytes] = {}
    for src_file in iter_files(source):
        relative = src_file.relative_to(source)
        expected[target / relative] = src_file.read_bytes()
    expected[marker_path(target)] = marker.encode("utf-8")
    return expected


def check_skill(source: Path, target: Path, marker: str, root: Path) -> list[str]:
    errors: list[str] = []
    expected = expected_files(source, target, marker)

    if not target.exists():
        return [f"missing generated skill: {os.path.relpath(target, root)}"]

    actual_files = set(iter_files(target))
    expected_paths = set(expected)

    for path, data in expected.items():
        if not path.exists():
            errors.append(f"missing file: {os.path.relpath(path, root)}")
        elif path.read_bytes() != data:
            errors.append(f"out of sync: {os.path.relpath(path, root)}")

    for extra in sorted(actual_files - expected_paths):
        errors.append(f"unexpected file: {os.path.relpath(extra, root)}")

    return errors


def check_stale(target_dir: Path, expected_names: set[str], root: Path) -> list[str]:
    if not target_dir.is_dir():
        return []
    errors: list[str] = []
    for path in sorted(target_dir.iterdir()):
        if path.is_dir() and path.name not in expected_names and is_managed(path):
            errors.append(f"stale generated skill: {os.path.relpath(path, root)}")
    return errors


def copy_skill(source: Path, target: Path, marker: str) -> None:
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(source, target, ignore=shutil.ignore_patterns("__pycache__", ".DS_Store"))
    marker_path(target).write_text(marker, encoding="utf-8")


def check(skills: dict[str, Path], project: Project) -> list[str]:
    """How the project's copies differ from `skills`."""
    marker = marker_text(project)
    errors: list[str] = []
    for target_dir in project.paths("skill_targets"):
        errors.extend(check_stale(target_dir, set(skills), project.root))
        for name, source in skills.items():
            errors.extend(check_skill(source, target_dir / name, marker, project.root))
    for target_dir in dropped_targets(project):
        errors.extend(check_stale(target_dir, set(skills), project.root))
    return errors


def sync(skills: dict[str, Path], project: Project) -> list[Path]:
    """Copy `skills` into the project's skill_targets and remove the marked
    copies of other skills there and in its dropped template targets;
    returns the removed copies."""
    marker = marker_text(project)
    removed: list[Path] = []
    for target_dir in project.paths("skill_targets"):
        target_dir.mkdir(parents=True, exist_ok=True)
        for name, source in skills.items():
            copy_skill(source, target_dir / name, marker)
        removed.extend(prune(target_dir, set(skills)))
    for target_dir in dropped_targets(project):
        removed.extend(prune(target_dir, set(skills)))
    return removed


def prune(target_dir: Path, names: set[str]) -> list[Path]:
    """Remove the marked copies in `target_dir` of skills not in `names`;
    returns them."""
    removed: list[Path] = []
    for path in sorted(target_dir.iterdir()) if target_dir.is_dir() else []:
        if path.is_dir() and path.name not in names and is_managed(path):
            shutil.rmtree(path)
            removed.append(path)
    return removed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="trazo agents",
                                     description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="validate without writing")
    args = parser.parse_args(argv)

    try:
        skills = canonical_skills(PROJECT)
    except SkillError as exc:
        raise SystemExit(str(exc)) from None
    if args.check:
        errors = check(skills, PROJECT)
        for error in errors:
            print(error, file=sys.stderr)
        if errors:
            return 1
    else:
        sync(skills, PROJECT)
    action = "checked" if args.check else "synced"
    print(f"Agent workflows {action}: {len(skills)} skills")
    return 0


if __name__ == "__main__":
    sys.exit(main())
